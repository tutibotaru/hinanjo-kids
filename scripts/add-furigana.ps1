function SafeReplace {
    param([string]$inText, [string]$inOld, [string]$inNew)
    # \r\n を除外しないと改行をまたぐ巨大マッチが発生し、ruby tag 外の漢字を
    # 「中身」と誤認して置換漏れになる。
    $pattern = '(\{[^|}\r\n]+\|[^|}\r\n]+\})'
    $parts = [regex]::Split($inText, $pattern)
    $sb = New-Object System.Text.StringBuilder
    foreach ($part in $parts) {
        if ($part -match '^\{[^|}\r\n]+\|[^|}\r\n]+\}$') {
            [void]$sb.Append($part)
        } else {
            [void]$sb.Append($part.Replace($inOld, $inNew))
        }
    }
    return $sb.ToString()
}

